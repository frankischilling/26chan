-- Operator-owned network rules share the content-admission generation lock.
-- No production ranges, ASNs or browser signatures are installed by migration.
SET LOCAL ROLE board_thread_transfer_owner;
DO $$ BEGIN
 PERFORM singleton FROM post_secrets.thread_transfer_catalog WHERE singleton FOR UPDATE;
 IF NOT FOUND OR content.text_thread_transfer_ready() IS DISTINCT FROM true THEN
  RAISE EXCEPTION 'Transfer catalog has drifted before network admission migration'; END IF;
END $$;
RESET ROLE;

CREATE TABLE admission.network_rules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0),
    position integer NOT NULL DEFAULT 0,
    active boolean NOT NULL DEFAULT true,
    range_start bigint CHECK(range_start BETWEEN 0 AND 4294967295),
    range_end bigint CHECK(range_end BETWEEN 0 AND 4294967295),
    asn bigint CHECK(asn BETWEEN 1 AND 4294967295),
    created_at bigint NOT NULL DEFAULT floor(extract(epoch FROM clock_timestamp()))::bigint CHECK(created_at>=0),
    updated_at bigint NOT NULL DEFAULT 0 CHECK(updated_at>=0),
    expires_at bigint NOT NULL DEFAULT 0 CHECK(expires_at>=0),
    boards text NOT NULL DEFAULT '' CHECK(octet_length(boards)<=1408
        AND boards ~ '^([a-z0-9]{1,10}|_ws_)?(,([a-z0-9]{1,10}|_ws_)?)*$'
        AND cardinality(string_to_array(boards,','))<=128),
    ops_only boolean NOT NULL DEFAULT false,
    images_only boolean NOT NULL DEFAULT false,
    reports_only boolean NOT NULL DEFAULT false,
    leniency smallint NOT NULL DEFAULT 0 CHECK(leniency BETWEEN 0 AND 3),
    signatures text NOT NULL DEFAULT '' CHECK(octet_length(signatures)<=2048 AND signatures !~ '[[:cntrl:]]'),
    CHECK((range_start IS NULL)=(range_end IS NULL)),
    CHECK(range_start IS NULL OR range_start<=range_end),
    CHECK(range_start IS NOT NULL OR asn IS NOT NULL)
);
-- Ordinary operator edits refresh the leniency anchor. An explicit changed
-- timestamp remains available for deliberate historical imports/corrections.
CREATE FUNCTION admission.stamp_network_update() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at:=floor(extract(epoch FROM clock_timestamp()))::bigint;
    END IF;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION admission.stamp_network_update() FROM PUBLIC;
CREATE TRIGGER network_update_clock BEFORE UPDATE ON admission.network_rules
    FOR EACH ROW EXECUTE FUNCTION admission.stamp_network_update();
CREATE INDEX network_rules_order ON admission.network_rules(leniency,position,id) WHERE active;
CREATE TRIGGER network_rules_changed AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON admission.network_rules
    FOR EACH STATEMENT EXECUTE FUNCTION admission.changed();
GRANT SELECT ON admission.network_rules TO board_admission_owner;

CREATE FUNCTION content.network_admission_rules(p_board text,p_now bigint)
RETURNS TABLE(id bigint,range_start bigint,range_end bigint,asn bigint,active boolean,
    created_at bigint,updated_at bigint,expires_at bigint,boards text,ops_only boolean,
    images_only boolean,reports_only boolean,leniency smallint,signatures text)
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
    SELECT r.id,r.range_start,r.range_end,r.asn,r.active,r.created_at,r.updated_at,r.expires_at,
        r.boards,r.ops_only,r.images_only,r.reports_only,r.leniency,r.signatures
    FROM admission.network_rules r
    JOIN content.boards b ON b.slug=p_board AND NOT b.staff_only
    WHERE r.active AND p_now>=0 AND (r.expires_at=0 OR r.expires_at>p_now) AND (r.boards IN ('','0') OR p_board=ANY(string_to_array(r.boards,','))
        OR (b.worksafe AND '_ws_'=ANY(string_to_array(r.boards,','))))
    ORDER BY r.leniency,r.position,r.id LIMIT 129
$$;
GRANT SELECT(worksafe) ON content.boards TO board_admission_owner;
REVOKE ALL ON FUNCTION content.network_admission_rules(text,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION content.network_admission_rules(text,bigint) TO board_public,board_staff;
GRANT CREATE ON SCHEMA content TO board_admission_owner;
ALTER FUNCTION content.network_admission_rules(text,bigint) OWNER TO board_admission_owner;
REVOKE CREATE ON SCHEMA content FROM board_admission_owner;

SET LOCAL ROLE board_thread_transfer_owner;
UPDATE post_secrets.thread_transfer_catalog SET definition_hash=post_secrets.transfer_catalog_hash() WHERE singleton;
DO $$ BEGIN
 IF content.text_thread_transfer_ready() IS DISTINCT FROM true THEN
  RAISE EXCEPTION 'Network policy migration did not preserve transfer authority'; END IF;
END $$;
RESET ROLE;
