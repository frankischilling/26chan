CREATE FUNCTION content.attachment_upload_filename(p_job text,p_capability text)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE v_filename text;
BEGIN
    -- Preserve the insertion lock order and verify capability expiry after
    -- waiting. Unready or revoked media cannot create content-filter effects.
    PERFORM j.id FROM media.jobs j WHERE j.id=p_job FOR UPDATE;
    PERFORM content.check_attachment_upload(p_job,p_capability);
    SELECT j.filename INTO v_filename FROM media.jobs j WHERE j.id=p_job AND j.state='published'
        AND EXISTS(SELECT 1 FROM media.assets a WHERE a.job_id=j.id AND a.state='approved');
    IF NOT FOUND THEN RAISE EXCEPTION 'Attachment is not approved.' USING ERRCODE='P0001'; END IF;
    RETURN v_filename;
END $$;
REVOKE ALL ON FUNCTION content.attachment_upload_filename(text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION content.attachment_upload_filename(text,text) TO board_public;
GRANT CREATE ON SCHEMA content TO board_attachment_owner;
ALTER FUNCTION content.attachment_upload_filename(text,text) OWNER TO board_attachment_owner;
REVOKE CREATE ON SCHEMA content FROM board_attachment_owner;

CREATE FUNCTION content.stamp_content_autosage() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE v_rule text:=nullif(current_setting('board.content_autosage',true),'');
    v_revision text:=nullif(current_setting('board.content_admission_revision',true),'');
    v_peer text:=nullif(current_setting('board.content_admission_peer',true),'');
BEGIN
    IF v_rule IS NULL THEN RETURN NEW; END IF;
    IF v_rule !~ '^[1-9][0-9]{0,18}$' OR v_revision IS NULL OR v_revision !~ '^[1-9][0-9]{0,18}$'
        OR v_peer IS NULL OR NOT EXISTS(SELECT 1 FROM admission.policy p WHERE p.singleton AND p.revision=v_revision::bigint)
        OR NOT EXISTS(SELECT 1 FROM admission.rules r WHERE r.id=v_rule::bigint AND r.active AND r.autosage
            AND (r.board='' OR r.board=NEW.board))
        OR NOT EXISTS(SELECT 1 FROM admission.hits h WHERE h.rule_id=v_rule::bigint AND h.peer=v_peer::inet
            AND h.last_hit>clock_timestamp()-interval '1 hour') THEN
        RAISE EXCEPTION 'Content autosage authority is unavailable.' USING ERRCODE='23514';
    END IF;
    NEW.permasage:=true;
    RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION content.stamp_content_autosage() FROM PUBLIC;
CREATE TRIGGER stamp_content_autosage BEFORE INSERT ON content.threads
    FOR EACH ROW EXECUTE FUNCTION content.stamp_content_autosage();
GRANT CREATE ON SCHEMA content TO board_admission_owner;
ALTER FUNCTION content.stamp_content_autosage() OWNER TO board_admission_owner;
REVOKE CREATE ON SCHEMA content FROM board_admission_owner;
