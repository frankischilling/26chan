CREATE TABLE admission.file_rules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0),
    active boolean NOT NULL DEFAULT true,
    board text NOT NULL DEFAULT '' CHECK(board IN ('','_ws_') OR board ~ '^[a-z0-9]{1,10}$'),
    digest bytea NOT NULL CHECK(octet_length(digest)=16),
    mode smallint NOT NULL DEFAULT 0 CHECK(mode BETWEEN 0 AND 2),
    ban_days integer NOT NULL DEFAULT 0 CHECK(ban_days BETWEEN -1 AND 3650),
    quiet boolean NOT NULL DEFAULT false,
    public_reason text NOT NULL DEFAULT '' CHECK(octet_length(public_reason)<=4096),
    description text NOT NULL DEFAULT '' CHECK(octet_length(description)<=4096),
    CHECK(mode=1 OR ban_days=0)
);
CREATE INDEX file_rules_scope ON admission.file_rules(board,id) WHERE active;
CREATE TRIGGER file_rules_changed AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON admission.file_rules
    FOR EACH STATEMENT EXECUTE FUNCTION admission.changed();
GRANT SELECT ON admission.file_rules TO board_admission_owner;

CREATE FUNCTION content.file_admission_rules(p_board text)
RETURNS TABLE(id bigint,board text,digest bytea,mode smallint,ban_days integer,quiet boolean)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE v_worksafe boolean;
BEGIN
    -- The same generation lock serializes edits to text, network and file rules.
    -- Keep the lock until the posting transaction commits or rolls back.
    IF current_setting('transaction_isolation')<>'read committed' THEN
        RAISE EXCEPTION 'File policy requires read committed isolation.' USING ERRCODE='55000';
    END IF;
    SELECT b.worksafe INTO v_worksafe FROM content.boards b
        WHERE b.slug=p_board AND NOT b.staff_only;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Public board not found.' USING ERRCODE='P0002';
    END IF;
    PERFORM p.singleton FROM admission.policy p WHERE p.singleton FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Content admission policy is unavailable.' USING ERRCODE='55000';
    END IF;
    -- One extra row is a bounded overflow sentinel. The domain compiler refuses
    -- more than 128 rules, including ambiguous matching scopes.
    RETURN QUERY SELECT r.id,r.board,r.digest,r.mode,r.ban_days,r.quiet
        FROM admission.file_rules r WHERE r.active
        AND (r.board='' OR r.board=p_board OR (v_worksafe AND r.board='_ws_'))
        ORDER BY r.id LIMIT 129;
END $$;
REVOKE ALL ON FUNCTION content.file_admission_rules(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION content.file_admission_rules(text) TO board_public,board_staff;
GRANT CREATE ON SCHEMA content TO board_admission_owner;
ALTER FUNCTION content.file_admission_rules(text) OWNER TO board_admission_owner;
REVOKE CREATE ON SCHEMA content FROM board_admission_owner;

SET LOCAL ROLE board_thread_transfer_owner;
UPDATE post_secrets.thread_transfer_catalog SET definition_hash=post_secrets.transfer_catalog_hash() WHERE singleton;
DO $$ BEGIN
 IF content.text_thread_transfer_ready() IS DISTINCT FROM true THEN
  RAISE EXCEPTION 'File policy migration did not preserve transfer authority'; END IF;
END $$;
RESET ROLE;
